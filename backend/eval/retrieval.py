"""Offline retrieval evaluation: dense vs hybrid vs reranked schema search.

Runs the real local models (sentence-transformers embedder, cross-encoder)
but needs no database and no LLM key. Each question has a set of tables a
correct query must read: for the end-to-end cases in `cases.json` they are
extracted from the ground-truth SQL; `retrieval_cases.json` adds questions
that lean on exact column names and paraphrases.

Metrics per mode and table budget, over all questions:

- complete: every required table was handed to the SQL generator;
- recall: mean fraction of required tables handed over;
- MRR: reciprocal rank of the first required table among retrieved tables;
- tables: mean number of tables in the prompt (lower is a smaller prompt);
- p50 latency of the search itself.

The table budget caps how many tables search may pick before foreign-key
expansion; small budgets stress the ranking. The run exits non-zero if a
hybrid or reranked mode completes fewer cases than plain dense retrieval.

Usage, from `backend/`:

    python -m eval.retrieval                 # writes ../docs/evaluation-retrieval.md
    python -m eval.retrieval --modes dense hybrid+rerank --budgets 1
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import statistics
import sys
import tempfile
import time
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import sqlglot
from sqlglot import exp

from app.core.config import Settings
from app.rag.embeddings import SentenceTransformerEmbedder
from app.rag.reranker import CrossEncoderReranker
from app.rag.schema_indexer import SchemaIndexer, build_schema_catalog
from app.rag.vector_store import FAISSVectorStore

HERE = Path(__file__).parent
MODES = ("dense", "hybrid", "dense+rerank", "hybrid+rerank")


@dataclass
class Case:
    id: str
    question: str
    tables: list[str]
    source: str


@dataclass
class ModeResult:
    case_id: str
    mode: str
    complete: bool
    recall: float
    reciprocal_rank: float
    tables: list[str]
    latency_ms: float


Results = dict[int, dict[str, list[ModeResult]]]  # table budget -> mode -> per case


def truth_tables(sql: str) -> list[str]:
    tree = sqlglot.parse_one(sql, read="postgres")
    return sorted({t.name for t in tree.find_all(exp.Table)})


def load_cases(cases_path: Path, retrieval_path: Path) -> list[Case]:
    cases = [
        Case(c["id"], c["question"], truth_tables(c["truth_sql"]), "end-to-end")
        for c in json.loads(cases_path.read_text(encoding="utf-8"))
        if c.get("kind", "accuracy") == "accuracy"
    ]
    cases += [
        Case(c["id"], c["question"], sorted(c["tables"]), "retrieval")
        for c in json.loads(retrieval_path.read_text(encoding="utf-8"))
    ]
    return cases


def score(indexer: SchemaIndexer, case: Case, budget: int) -> ModeResult:
    started = time.perf_counter()
    result = indexer.search(case.question, budget)
    latency = (time.perf_counter() - started) * 1000
    selected = result.table_names
    retrieved = [s.table for s in result.table_scores if s.via == "retrieved"]
    hits = [t for t in case.tables if t in selected]
    first = next((i for i, t in enumerate(retrieved, start=1) if t in case.tables), None)
    return ModeResult(
        case_id=case.id,
        mode=result.mode,
        complete=len(hits) == len(case.tables),
        recall=len(hits) / len(case.tables),
        reciprocal_rank=1 / first if first else 0.0,
        tables=selected,
        latency_ms=round(latency, 1),
    )


def summarise(results: list[ModeResult]) -> dict[str, Any]:
    return {
        "cases": len(results),
        "complete": sum(r.complete for r in results),
        "recall": round(statistics.fmean(r.recall for r in results), 3),
        "mrr": round(statistics.fmean(r.reciprocal_rank for r in results), 3),
        "mean_tables": round(statistics.fmean(len(r.tables) for r in results), 2),
        "p50_latency_ms": round(statistics.median(r.latency_ms for r in results), 1),
    }


def regressions(results: Results) -> list[str]:
    """Budgets where a hybrid or reranked mode completes fewer cases than dense."""
    found = []
    for budget, by_mode in results.items():
        if "dense" not in by_mode:
            continue
        baseline = summarise(by_mode["dense"])["complete"]
        for mode, mode_results in by_mode.items():
            if summarise(mode_results)["complete"] < baseline:
                found.append(f"{mode} below dense at table budget {budget}")
    return found


def render_markdown(cases: list[Case], results: Results, meta: dict[str, Any]) -> str:
    lines = [
        "# Retrieval evaluation",
        "",
        "Generated by `python -m eval.retrieval`: real local embedder and cross-encoder,",
        "no database or LLM involved. A case is *complete* when every table a correct",
        "query needs reaches the SQL generator. The *table budget* caps how many tables",
        "search may pick before foreign-key expansion; small budgets stress the ranking.",
        "",
        f"- **Run:** {meta['date']}",
        f"- **Embeddings:** `{meta['embedding_model']}`  ·  **Reranker:** `{meta['reranker']}` "
        f"(shortlist {meta['rerank_candidates']})",
        f"- **Cases:** {len(cases)} ({meta['end_to_end']} from `cases.json`, "
        f"{meta['retrieval_only']} from `retrieval_cases.json`)",
        f"- **Production default:** table budget {meta['default_budget']}",
        "",
        "| Table budget | Mode | Complete | Recall | MRR | Tables in prompt | p50 latency |",
        "|-------------:|------|---------:|-------:|----:|-----------------:|------------:|",
    ]
    for budget, by_mode in results.items():
        for mode, mode_results in by_mode.items():
            s = summarise(mode_results)
            lines.append(
                f"| {budget} | `{mode}` | {s['complete']}/{s['cases']} | {s['recall']:.3f} "
                f"| {s['mrr']:.3f} | {s['mean_tables']:.2f} | {s['p50_latency_ms']:.1f} ms |"
            )
    lines += [
        "",
        "Latency is the search alone, CPU only, on the machine that ran the evaluation.",
        "",
    ]
    for budget, by_mode in results.items():
        modes = list(by_mode)
        lines += [
            f"## Per case, table budget {budget}",
            "",
            "| Case | Needs | " + " | ".join(f"`{m}`" for m in modes) + " |",
            "|------|-------|" + "|".join("---" for _ in modes) + "|",
        ]
        for i, case in enumerate(cases):
            cells = []
            for m in modes:
                r = by_mode[m][i]
                mark = "pass" if r.complete else "**miss**"
                cells.append(f"{mark} · RR {r.reciprocal_rank:.2f} · {len(r.tables)}t")
            lines.append(f"| `{case.id}` | {', '.join(case.tables)} | " + " | ".join(cells) + " |")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    defaults = Settings.model_fields
    default_budget = int(defaults["retrieval_max_tables"].default)
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--cases", type=Path, default=HERE / "cases.json")
    parser.add_argument("--retrieval-cases", type=Path, default=HERE / "retrieval_cases.json")
    parser.add_argument(
        "--out", type=Path, default=HERE.parent.parent / "docs" / "evaluation-retrieval.md"
    )
    parser.add_argument("--modes", nargs="*", choices=MODES, default=list(MODES))
    parser.add_argument(
        "--budgets",
        nargs="*",
        type=int,
        default=sorted({1, 2, default_budget}),
        help="Table budgets (max tables before foreign-key expansion) to evaluate.",
    )
    parser.add_argument("--embedding-model", default=defaults["embedding_model"].default)
    parser.add_argument("--reranker-model", default=defaults["reranker_model"].default)
    parser.add_argument(
        "--rerank-candidates", type=int, default=defaults["retrieval_rerank_candidates"].default
    )
    args = parser.parse_args(argv)

    cases = load_cases(args.cases, args.retrieval_cases)
    results: Results = {}
    with tempfile.TemporaryDirectory(prefix="rag-retrieval-eval-") as tmp:
        store = FAISSVectorStore(
            SentenceTransformerEmbedder(args.embedding_model), Path(tmp) / "index"
        )
        reranker = CrossEncoderReranker(args.reranker_model)
        catalog = build_schema_catalog()
        SchemaIndexer(store, catalog).index()
        store.warm_up()
        reranker.warm_up()

        for budget in args.budgets:
            results[budget] = {}
            print(f"table budget {budget}")
            for mode in args.modes:
                indexer = SchemaIndexer(
                    store,
                    catalog,
                    hybrid=mode.startswith("hybrid"),
                    reranker=reranker if mode.endswith("+rerank") else None,
                    rerank_candidates=args.rerank_candidates,
                )
                mode_results = [score(indexer, case, budget) for case in cases]
                results[budget][mode] = mode_results
                s = summarise(mode_results)
                print(
                    f"  {mode:<14} complete {s['complete']:>2}/{s['cases']}  "
                    f"recall {s['recall']:.3f}  MRR {s['mrr']:.3f}  "
                    f"tables {s['mean_tables']:.2f}  p50 {s['p50_latency_ms']}ms"
                )
                for case, r in zip(cases, mode_results, strict=True):
                    if not r.complete:
                        print(f"      miss {case.id}: needs {case.tables}, got {r.tables}")

    meta = {
        "date": dt.datetime.now(dt.UTC).strftime("%Y-%m-%d %H:%M UTC"),
        "embedding_model": args.embedding_model,
        "reranker": args.reranker_model,
        "rerank_candidates": args.rerank_candidates,
        "default_budget": default_budget,
        "end_to_end": sum(c.source == "end-to-end" for c in cases),
        "retrieval_only": sum(c.source == "retrieval" for c in cases),
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render_markdown(cases, results, meta) + "\n", encoding="utf-8")
    payload = {
        "meta": meta,
        "summary": {
            str(b): {m: summarise(r) for m, r in by_mode.items()} for b, by_mode in results.items()
        },
        "results": {
            str(b): {m: [asdict(x) for x in r] for m, r in by_mode.items()}
            for b, by_mode in results.items()
        },
    }
    args.out.with_suffix(".json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"-> {args.out}")

    failures = regressions(results)
    for failure in failures:
        print(f"REGRESSION: {failure}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
