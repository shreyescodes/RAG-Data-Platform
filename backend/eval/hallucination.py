"""Hallucination-detector evaluation on labelled answer claims.

Each case in `hallucination_cases.json` holds the evidence an answer was
generated from (result rows, live data) and a set of claims labelled
`faithful` or `hallucinated`. The hallucinated ones are deliberate:
fabricated values, correct values attributed to the wrong entity, wrong
counts and dates, invented companies, unsupported qualitative statements.

A hallucinated claim is *caught* when the detector marks it unsupported or
partially supported; a faithful claim so marked is a *false positive*.
"Unverifiable" is neither: it is reported separately.

Usage, from `backend/`:

    python -m eval.hallucination                     # deterministic checks only
    python -m eval.hallucination --modes heuristic hybrid   # hybrid needs an LLM

The run exits non-zero when heuristic recall falls below --min-recall or its
false-positive rate exceeds --max-fpr.
"""

from __future__ import annotations

import argparse
import asyncio
import datetime as dt
import json
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

from app.agents.base import Trace
from app.agents.verification import VerificationAgent
from app.core.config import get_settings
from app.core.logging import configure_logging
from app.services.llm import OpenAICompatibleChatModel
from app.services.structured_output import StructuredOutputExtractor

HERE = Path(__file__).parent
FLAGGED = ("unsupported", "partially_supported")


@dataclass
class ClaimResult:
    case_id: str
    mode: str
    text: str
    label: str
    category: str
    verdict: str
    method: str
    reason: str

    @property
    def flagged(self) -> bool:
        return self.verdict in FLAGGED


async def run_case(agent: VerificationAgent, case: dict[str, Any]) -> list[ClaimResult]:
    texts = [c["text"] for c in case["claims"]]
    report = await agent.run(
        case["question"],
        case.get("rows", []),
        case.get("enrichment", {}),
        answer="",
        insights=texts,
        trace=Trace(),
    )
    by_text = {c.text: c for c in report.claims}
    results = []
    for claim in case["claims"]:
        checked = by_text.get(claim["text"])
        if checked is None:  # pragma: no cover - a case that splits into several claims
            raise ValueError(f"claim did not survive extraction intact: {claim['text']!r}")
        results.append(
            ClaimResult(
                case_id=case["id"],
                mode=agent.mode,
                text=claim["text"],
                label=claim["label"],
                category=claim["category"],
                verdict=checked.verdict,
                method=checked.method,
                reason=checked.reason,
            )
        )
    return results


def summarise(results: list[ClaimResult]) -> dict[str, Any]:
    hallucinated = [r for r in results if r.label == "hallucinated"]
    faithful = [r for r in results if r.label == "faithful"]
    caught = sum(r.flagged for r in hallucinated)
    false_pos = sum(r.flagged for r in faithful)
    flagged = caught + false_pos
    return {
        "claims": len(results),
        "hallucinated": len(hallucinated),
        "caught": caught,
        "recall": round(caught / len(hallucinated), 3) if hallucinated else None,
        "faithful": len(faithful),
        "false_positives": false_pos,
        "false_positive_rate": round(false_pos / len(faithful), 3) if faithful else None,
        "precision": round(caught / flagged, 3) if flagged else None,
        "faithful_confirmed": sum(r.verdict == "supported" for r in faithful),
        "unverifiable": sum(r.verdict == "unverifiable" for r in results),
    }


def render_markdown(by_mode: dict[str, list[ClaimResult]], meta: dict[str, Any]) -> str:
    lines = [
        "# Hallucination detection evaluation",
        "",
        "Generated by `python -m eval.hallucination` from `eval/hallucination_cases.json`:",
        "answer claims labelled faithful or hallucinated against the rows and live data",
        "they were written from. A hallucinated claim is *caught* when it is marked",
        "unsupported or partially supported; a faithful claim so marked is a false positive.",
        "",
        f"- **Run:** {meta['date']}",
        f"- **Judge model (hybrid):** `{meta['model'] or 'not used'}`",
        "",
        "| Mode | Caught | Recall | False positives | Precision | Faithful confirmed "
        "| Unverifiable |",
        "|------|-------:|-------:|----------------:|----------:|-------------------:"
        "|-------------:|",
    ]
    for mode, results in by_mode.items():
        s = summarise(results)
        lines.append(
            f"| `{mode}` | {s['caught']}/{s['hallucinated']} | {s['recall']:.2f} "
            f"| {s['false_positives']}/{s['faithful']} | {s['precision'] or 0:.2f} "
            f"| {s['faithful_confirmed']}/{s['faithful']} | {s['unverifiable']} |"
        )

    modes = list(by_mode)
    lines += ["", "## By category (hallucinated claims caught)", ""]
    lines.append("| Category | " + " | ".join(f"`{m}`" for m in modes) + " |")
    lines.append("|----------|" + "|".join("---:" for _ in modes) + "|")
    first = by_mode[modes[0]]
    categories = sorted({r.category for r in first if r.label == "hallucinated"})
    for category in categories:
        cells = []
        for m in modes:
            group = [r for r in by_mode[m] if r.category == category and r.label == "hallucinated"]
            cells.append(f"{sum(r.flagged for r in group)}/{len(group)}")
        lines.append(f"| {category} | " + " | ".join(cells) + " |")

    lines += ["", "## Every claim", ""]
    lines.append("| Case | Claim | Label | " + " | ".join(f"`{m}`" for m in modes) + " |")
    lines.append("|------|-------|-------|" + "|".join("---" for _ in modes) + "|")
    for i, r in enumerate(first):
        cells = []
        for m in modes:
            other = by_mode[m][i]
            wrong = other.flagged != (other.label == "hallucinated") and other.verdict != (
                "unverifiable"
            )
            mark = f"**{other.verdict}**" if wrong else other.verdict
            cells.append(mark)
        lines.append(f"| `{r.case_id}` | {r.text} | {r.label} | " + " | ".join(cells) + " |")
    lines += ["", "Bold verdicts are errors: a missed hallucination or a false positive."]
    return "\n".join(lines)


async def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--cases", type=Path, default=HERE / "hallucination_cases.json")
    parser.add_argument(
        "--out", type=Path, default=HERE.parent.parent / "docs" / "evaluation-hallucination.md"
    )
    parser.add_argument(
        "--modes", nargs="*", choices=("heuristic", "hybrid"), default=["heuristic"]
    )
    parser.add_argument("--min-recall", type=float, default=0.8)
    parser.add_argument("--max-fpr", type=float, default=0.05)
    args = parser.parse_args(argv)
    configure_logging("WARNING")

    cases = json.loads(args.cases.read_text(encoding="utf-8"))
    settings = get_settings()
    chat: OpenAICompatibleChatModel | None = None
    if "hybrid" in args.modes:
        chat = OpenAICompatibleChatModel(
            api_key=settings.llm_api_key.get_secret_value(),
            base_url=settings.llm_base_url,
            model=settings.llm_model,
            timeout_seconds=max(settings.llm_timeout_seconds, 120),
            max_retries=settings.llm_max_retries,
        )

    by_mode: dict[str, list[ClaimResult]] = {}
    try:
        for mode in args.modes:
            extractor = (
                StructuredOutputExtractor(
                    chat,
                    max_attempts=settings.llm_structured_max_attempts,
                    mode=settings.llm_structured_output,
                )
                if mode == "hybrid" and chat is not None
                else None
            )
            agent = VerificationAgent(mode=mode, extractor=extractor)
            started = time.perf_counter()
            results = [r for case in cases for r in await run_case(agent, case)]
            by_mode[mode] = results
            s = summarise(results)
            print(
                f"{mode:<10} caught {s['caught']}/{s['hallucinated']} (recall {s['recall']})  "
                f"false positives {s['false_positives']}/{s['faithful']}  "
                f"unverifiable {s['unverifiable']}  {time.perf_counter() - started:.1f}s"
            )
            for r in results:
                if r.flagged != (r.label == "hallucinated"):
                    print(f"    {r.label:<12} {r.verdict:<20} {r.text}  [{r.reason}]")
    finally:
        if chat is not None:
            await chat.aclose()

    meta = {
        "date": dt.datetime.now(dt.UTC).strftime("%Y-%m-%d %H:%M UTC"),
        "model": settings.llm_model if "hybrid" in args.modes else None,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render_markdown(by_mode, meta) + "\n", encoding="utf-8")
    payload = {
        "meta": meta,
        "summary": {m: summarise(r) for m, r in by_mode.items()},
        "results": {m: [asdict(x) for x in r] for m, r in by_mode.items()},
    }
    args.out.with_suffix(".json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"-> {args.out}")

    gate = summarise(by_mode["heuristic"]) if "heuristic" in by_mode else None
    if gate is not None and (
        (gate["recall"] or 0) < args.min_recall or (gate["false_positive_rate"] or 0) > args.max_fpr
    ):
        print(f"FAIL: heuristic recall {gate['recall']} / FPR {gate['false_positive_rate']}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
