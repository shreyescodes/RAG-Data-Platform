"""Load test for `POST /api/query`.

Sends the same mix of questions at increasing concurrency and reports latency
percentiles, throughput and errors. Point it at a backend whose LLM is
`eval.stub_llm` to measure the platform rather than a provider's rate limits.

    python -m eval.load --url http://backend:8000 --api-key KEY --out ../docs/load-test.md
"""

from __future__ import annotations

import argparse
import asyncio
import datetime as dt
import statistics
import time
from dataclasses import dataclass
from pathlib import Path

import httpx

QUESTIONS = (
    "NVDA closing price and 50-day moving average for the last 30 trading days",
    "What were Berkshire Hathaway's 5 largest holdings?",
    "Apple's quarterly revenue for the last four quarters",
    "List the Technology companies",
)


@dataclass
class Level:
    concurrency: int
    requests: int
    errors: int
    seconds: float
    latencies: list[float]

    def percentile(self, q: float) -> float:
        ordered = sorted(self.latencies)
        return ordered[min(len(ordered) - 1, round(q * (len(ordered) - 1)))] if ordered else 0.0

    @property
    def throughput(self) -> float:
        return self.requests / self.seconds if self.seconds else 0.0


async def _run_level(client: httpx.AsyncClient, concurrency: int, total: int) -> Level:
    queue: asyncio.Queue[int] = asyncio.Queue()
    for i in range(total):
        queue.put_nowait(i)
    latencies: list[float] = []
    errors = 0

    async def worker() -> None:
        nonlocal errors
        while not queue.empty():
            i = queue.get_nowait()
            started = time.perf_counter()
            try:
                response = await client.post(
                    "/api/query", json={"query": QUESTIONS[i % len(QUESTIONS)]}
                )
                ok = response.status_code == 200 and response.json().get("success") is True
            except httpx.HTTPError:
                ok = False
            latencies.append(time.perf_counter() - started)
            errors += not ok

    started = time.perf_counter()
    await asyncio.gather(*(worker() for _ in range(concurrency)))
    return Level(concurrency, total, errors, time.perf_counter() - started, latencies)


def _markdown(levels: list[Level], args: argparse.Namespace) -> str:
    lines = [
        "# Load test",
        "",
        "Generated by `python -m eval.load` against the real backend and PostgreSQL, with",
        "the LLM replaced by `eval.stub_llm` (a fixed "
        f"{args.llm_delay:g} s per call) and the LLM caches off, so every request runs",
        "retrieval, SQL execution and the fact check. It measures the platform, not the",
        "model provider: a hosted LLM adds its own latency and rate limits on top.",
        "",
        f"- **Run:** {dt.datetime.now(dt.UTC):%Y-%m-%d %H:%M UTC}",
        f"- **Setup:** {args.setup}",
        f"- **Requests per level:** {args.requests}",
        "",
        "| Concurrent users | Requests/s | p50 | p95 | Max | Errors |",
        "|-----------------:|-----------:|----:|----:|----:|-------:|",
    ]
    lines += [
        f"| {lv.concurrency} | {lv.throughput:.1f} | {lv.percentile(0.5):.2f} s "
        f"| {lv.percentile(0.95):.2f} s | {max(lv.latencies):.2f} s | {lv.errors} |"
        for lv in levels
    ]
    return "\n".join(lines) + "\n"


async def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--url", default="http://localhost:8000")
    parser.add_argument("--api-key", default="")
    parser.add_argument("--levels", default="1,5,10,20")
    parser.add_argument("--requests", type=int, default=40)
    parser.add_argument("--llm-delay", type=float, default=0.5)
    parser.add_argument("--setup", default="one uvicorn worker")
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()

    headers = {"X-API-Key": args.api_key} if args.api_key else {}
    async with httpx.AsyncClient(base_url=args.url, headers=headers, timeout=120) as client:
        await _run_level(client, 1, 2)  # warm up
        levels = []
        for concurrency in (int(c) for c in args.levels.split(",")):
            level = await _run_level(client, concurrency, args.requests)
            levels.append(level)
            print(
                f"{concurrency:>3} users  {level.throughput:5.1f} req/s  "
                f"p50 {statistics.median(level.latencies):.2f}s  "
                f"p95 {level.percentile(0.95):.2f}s  errors {level.errors}",
                flush=True,
            )
    report = _markdown(levels, args)
    if args.out:
        args.out.write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    asyncio.run(main())
